            <h4 class="text-secondary fw-normal">Psychometric Assessments</h4>
            <p class="text-muted mt-2">For Psychometric Assessments & Career Counseling at Pharos Education Consultancy</p>
        </header>

        <section class="mb-5 lead">
            <p>At Pharos Education Consultancy, career counseling is not just a service—it is a responsibility. Every assessment, report, recommendation, and Counseling interaction impacts a student’s long-term academic, professional, and emotional journey.</p>
            <p>This Code of Conduct defines the ethical framework, professional standards, and responsible practices followed by Pharos Education Consultancy, its certified career counsellors, partners, schools, and institutions.</p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">1. Purpose & Ethical Philosophy</h2>
            <p>Pharos Education Consultancy is committed to:</p>
            <ul class="mb-3">
                <li class="mb-2">Student-first decision making</li>
                <li class="mb-2">Scientific, unbiased career assessments</li>
                <li class="mb-2">Long-term career wellbeing, not short-term outcomes</li>
                <li class="mb-2">Responsible use of psychometric data and AI</li>
            </ul>
            <div class="alert alert-primary fw-bold" role="alert">
                Career guidance must empower—not influence or manipulate—choices.
            </div>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">2. Scientific Integrity of Psychometric Assessments</h2>
            <p>We strictly ensure that:</p>
            <ul class="mb-3">
                <li class="mb-2">Assessments are research-based, validated, and periodically reviewed</li>
                <li class="mb-2">Questions measure aptitude, interest, personality, and potential—not academic marks alone</li>
                <li class="mb-2">No assessment claims to predict success, guarantee outcomes, or label intelligence</li>
                <li class="mb-2">Results are interpreted holistically, not in isolation</li>
            </ul>
            <p class="fw-bold text-danger">
                🚫 No shortcuts, no pseudo-science, no generic quizzes.
            </p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">3. Ethical Use of Assessment Results</h2>
            <p>Pharos Education Consultancy follows these principles:</p>
            <ul class="mb-3">
                <li class="mb-2">Assessment results are guidance tools, not final decisions</li>
                <li class="mb-2">Students are never forced into a career, course, or institution</li>
                <li class="mb-2">Counsellors explain results in simple, non-judgmental language</li>
                <li class="mb-2">Reports highlight multiple suitable pathways, not a single rigid option</li>
                <li class="mb-2">Limitations of assessments are clearly communicated</li>
            </ul>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">4. Student & Parent-Centric Counseling</h2>
            <p>Our Counseling approach ensures:</p>
            <ul class="mb-3">
                <li class="mb-2">Respect for individual aspirations, family context, and socio-economic realities</li>
                <li class="mb-2">Emotional sensitivity during critical decision stages (Class 8–12, graduation, career switches)</li>
                <li class="mb-2">No fear-based Counseling or pressure tactics</li>
                <li class="mb-2">Encouragement of informed choice, not counsellor bias</li>
            </ul>
            <div class="alert alert-success fw-bold" role="alert">
                Career Counseling must reduce anxiety—not create it.
            </div>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">5. Data Privacy, Confidentiality & Security</h2>
            <p>Pharos Education Consultancy strictly adheres to global data protection standards. We ensure:</p>
            <ul class="mb-3">
                <li class="mb-2">Personal and psychometric data is secure, encrypted, and access-controlled</li>
                <li class="mb-2">Data is used only for Counseling and guidance purposes</li>
                <li class="mb-2">No selling, sharing, or commercial misuse of student data</li>
                <li class="mb-2">Clear consent mechanisms for data collection and usage</li>
                <li class="mb-2">Compliance with Data Security norms, India IT Act, and applicable international regulations</li>
            </ul>
            <p class="fw-bold text-primary">
                🔒 Student data belongs to the student—always.
            </p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">6. No Conflict of Interest Policy</h2>
            <p>Pharos Education Consultancy maintains strict neutrality:</p>
            <ul class="mb-3">
                <li class="mb-2">Counsellors do not push colleges, courses, or countries for commissions</li>
                <li class="mb-2">Career recommendations are independent of admission or business incentives</li>
                <li class="mb-2">Admissions guidance is offered only after career clarity</li>
                <li class="mb-2">Transparent disclosure of any partnerships or affiliations</li>
            </ul>
            <p class="fw-bold">
                Career Counseling and admissions Counseling are treated as distinct ethical processes.
            </p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">7. Responsible Use of AI & Technology</h2>
            <p>As a CareerTech company, Pharos Education Consultancy ensures:</p>
            <ul class="mb-3">
                <li class="mb-2">AI is used to assist counsellors, not replace human judgement</li>
                <li class="mb-2">No automated decision-making without expert oversight</li>
                <li class="mb-2">AI outputs are reviewed for bias, accuracy, and fairness</li>
                <li class="mb-2">Continuous monitoring to prevent algorithmic discrimination</li>
            </ul>
            <div class="alert alert-info fw-bold" role="alert">
                Technology enhances Counseling—it never overrides human responsibility.
            </div>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">8. Professional Standards for Career Counsellors</h2>
            <p>All Pharos Education Consultancy-associated counsellors must:</p>
            <ul class="mb-3">
                <li class="mb-2">Be trained and certified in psychometric interpretation</li>
                <li class="mb-2">Follow structured Counseling frameworks and SOPs</li>
                <li class="mb-2">Maintain professional boundaries and ethical communication</li>
                <li class="mb-2">Engage in continuous learning and upskilling</li>
                <li class="mb-2">Avoid exaggerated claims or guarantees</li>
            </ul>
            <p class="fw-bold text-danger">
                Unethical practices lead to strict corrective action or de-association.
            </p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">9. Transparency & Honest Communication</h2>
            <p>We believe trust is built through clarity:</p>
            <ul class="mb-3">
                <li class="mb-2">Clear explanation of assessment scope and outcomes</li>
                <li class="mb-2">No misleading marketing claims</li>
                <li class="mb-2">Realistic career outlooks, not hype-driven narratives</li>
                <li class="mb-2">Honest discussion of effort, skills, and long-term planning required</li>
            </ul>
            <p class="fw-bold">
                Career guidance must be realistic, not aspirational fiction.
            </p>
        </section>

        <section class="mb-5">
            <h2 class="h4 fw-bold border-bottom pb-2">10. Continuous Review & Accountability</h2>
            <p>Pharos Education Consultancy commits to:</p>
            <ul class="mb-3">
                <li class="mb-2">Regular audits of assessments and Counseling practices</li>
                <li class="mb-2">Feedback-driven improvement from students, parents, and institutions</li>
                <li class="mb-2">Updating ethical guidelines as careers, technology, and regulations evolve</li>
            </ul>
            <div class="alert alert-secondary fw-bold text-center mb-0" role="alert">
                Ethics is not static—it grows with responsibility.
            </div>
        </section>

